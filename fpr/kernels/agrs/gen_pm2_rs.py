#!/usr/bin/env python3
"""agrs: generate pm2_rs.cu = RSF (the RS push fused into the production MoE's combine) on
moe_prefill's pm2.cu, the host file of pmv.FusedV (ENG_PM_NT: production's moe_prefill.cu kernels with the narrow-tile /
wait patches, frozen snapshot 3).

pm2_rs.cu is pm2.cu (frozen snapshot copy, read-only) with exactly the edits pm_rs.cu made to pm_fused.cu:
  1. the agrs block (red.release / fence helpers, RsPeers, k_pm_combine_push) copied verbatim from pm_rs.cu, inserted
     after k_pm_combine (the generator asserts pm2.cu's k_pm_combine is byte-identical to the one pm_rs.cu's
     k_pm_combine_push was derived from);
  2. pm_layer -> static pm_layer_impl(..., rp, rank, epoch, grid), whose combine launch becomes k_pm_combine_push when
     rp != nullptr (after the shared slice's join, sh_done);
  3. the pm_layer / pm_layer_rs wrappers copied verbatim from pm_rs.cu, and the layer_rs binding.
Everything else (pm_layer8, set_overlap, shared_slice, ...) is pm2.cu verbatim.
  python3 gen_pm2_rs.py [--src <pm2.cu>] [--out pm2_rs.cu]      (agrs_pmnt.py runs it before building)"""
from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent
PHYS = Path(os.environ.get("PHYS_ROOT", str(HERE.parent.parent)))
SRC = PHYS / "kernels" / "moe_prefill" / "build" / "pmv_frozen3_src" / "pm2.cu"
OUT = HERE / "pm2_rs.cu"


def cut(txt: str, a: str, b: str, incl_b: bool = False) -> str:
    i = txt.index(a)
    j = txt.index(b, i)
    return txt[i: j + (len(b) if incl_b else 0)]


def one(txt: str, old: str, new: str) -> str:
    assert txt.count(old) == 1, f"expected exactly one occurrence of: {old[:80]!r}"
    return txt.replace(old, new)


def generate(src: Path = SRC) -> str:
    pm2 = src.read_text()
    rs = (HERE / "pm_rs.cu").read_text()
    comb_a = "// k_pm_combine: production's moe_combine_kernel"
    comb_b = "  *reinterpret_cast<uint4*>(out + size_t(p) * H + c) = pack8_bf16(acc);\n}\n"
    assert cut(pm2, comb_a, comb_b, True) == cut(rs, comb_a, comb_b, True), "pm2.cu's k_pm_combine differs from pm_rs.cu's"
    agrs_block = cut(rs, "__device__ __forceinline__ void agrs_red_release_sys", "\nvoid check_bf16_rows")
    wrappers = cut(rs, "void pm_layer(torch::Tensor fall", "PYBIND11_MODULE(")
    rs_call = cut(rs, "  if (rp != nullptr) {  // agrs RSF", "  const long n = long(Tall) * (H / 8);")
    out = pm2
    # 1. the agrs block after k_pm_combine (before pm2's act8 section)
    out = one(out, comb_b + "\n// ---- act8", comb_b + "\n" + agrs_block + "\n// ---- act8")
    # 2. pm_layer -> pm_layer_impl with the RS peers; the combine launch -> k_pm_combine_push when rp is set
    sig = ("void pm_layer(torch::Tensor fall, torch::Tensor gr, torch::Tensor nv, int64_t R, int64_t vcount, torch::Tensor w13, torch::Tensor s13,\n"
           "              torch::Tensor w2, torch::Tensor s2, torch::Tensor sw13, torch::Tensor sw2, torch::Tensor gu, torch::Tensor hsh,\n"
           "              torch::Tensor sh, torch::Tensor part, double limit, int64_t variant, bool padded, c10::optional<torch::Tensor> fvbuf) {\n")
    out = one(out, sig, "static " + sig.replace("void pm_layer(", "void pm_layer_impl(").replace(
        "c10::optional<torch::Tensor> fvbuf) {\n",
        "c10::optional<torch::Tensor> fvbuf,\n                          const RsPeers* rp, int rank, unsigned* epoch, int grid) {\n"))
    comb_launch = "  const long n = long(Tall) * (H / 8);\n  if (sh_done) sh_done->block(stream);\n  k_pm_combine<<<"
    out = one(out, comb_launch, "  if (sh_done) sh_done->block(stream);\n" + rs_call + "  const long n = long(Tall) * (H / 8);\n  k_pm_combine<<<")
    # 3. the wrappers (pm_layer, pm_layer_rs) after pm_layer_impl, and the binding
    out = one(out, "// act8 layer (opt-in, LOSSY on the prefill rows)", wrappers + "// act8 layer (opt-in, LOSSY on the prefill rows)")
    bind = "  ds41h_prefill_bind(m);  // production's moe_prefill.cu bindings (moe_forward, set_hybrid, moe_gemm, moe_permute, ...)\n"
    out = one(out, bind, bind + '  m.def("layer_rs", &pm_layer_rs, "agrs RSF: pm_layer with the combine storing into the owners\' '
              'RS receive slots");\n')
    md5 = hashlib.md5(pm2.encode()).hexdigest()
    head = (f"// GENERATED by kernels/agrs/gen_pm2_rs.py from {src} (md5 {md5}): RSF on moe_prefill's\n"
            "// pm2.cu (pmv.FusedV's host file). Do not edit; edit the generator. The only edits vs pm2.cu are pm_rs.cu's RSF\n"
            "// additions (agrs block, pm_layer_impl with the RS peers, layer_rs entry); see gen_pm2_rs.py.\n")
    return head + out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=str(SRC))
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()
    txt = generate(Path(a.src))
    p = Path(a.out)
    if not p.exists() or p.read_text() != txt:
        p.write_text(txt)
        print(f"wrote {p}", flush=True)
    else:
        print(f"{p} unchanged", flush=True)


if __name__ == "__main__":
    main()
